import assert from 'node:assert/strict'
import { randomBytes, randomUUID } from 'node:crypto'
import { copyFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { projectRoot, startIsolatedPostgres } from './isolated-environment.mjs'
import { listMigrationFiles } from '../packages/database-readiness/index.js'
import { BillingStore } from '../packages/enterprise-ai/billing.js'
import { PlatformAiStore, EnterpriseAiStore, SELF_SERVICE_AI_BASE_URL } from '../packages/enterprise-ai/index.js'

assert.ok(process.argv[2], 'Explicit isolated PostgreSQL bin directory required; no business fallback')
const instance = await startIsolatedPostgres(process.argv[2])
for (const key of Object.keys(process.env)) delete process.env[key]
Object.assign(process.env, instance.env, {
  OPENAI_BASE_URL: 'https://platform.example/v1', OPENAI_API_KEY: 'synthetic-platform-key', OPENAI_MODEL: 'platform-model',
})
const require = createRequire(join(projectRoot, 'apps/api/package.json'))
require(join(projectRoot, 'scripts/isolated-network-guard.cjs'))
const { Pool } = require('pg')
const admin = new Pool(instance.connection)
const masterKey = randomBytes(32).toString('base64')
const org = randomUUID(), other = randomUUID(), actor = randomUUID(), outsider = randomUUID(), member = randomUUID(), system = randomUUID()
const schema = 'company_' + org.replaceAll('-', '')
const otherSchema = 'company_' + other.replaceAll('-', '')
let pool, companyPool, otherPool, created = false
const checks = []
async function check(name, action) { await action(); checks.push(name); console.log('PASS ' + name) }
try {
  assert.equal((await admin.query('SHOW cluster_name')).rows[0].cluster_name, instance.cluster)
  await admin.query('CREATE DATABASE "' + instance.database + '"'); created = true
  const connection = { ...instance.connection, database: instance.database }
  pool = new Pool(connection)
  const { runMigrations } = await import(pathToFileURL(join(projectRoot, 'apps/api/dist/src/db/migrations.js')))
  const migrations = join(projectRoot, 'db/migrations')
  const baseline = join(instance.directory, 'baseline-migrations')
  await mkdir(baseline)
  for (const migration of await listMigrationFiles(migrations)) {
    if (migration.version < '0108') await copyFile(migration.path, join(baseline, migration.name))
  }
  await runMigrations(pool, baseline)
  await pool.query("INSERT INTO public.organizations(id,name,kind,service_status) VALUES($1,'synthetic-ai-a','test','enabled'),($2,'synthetic-ai-b','test','enabled')", [org, other])
  await pool.query("INSERT INTO public.users(id,email,display_name) VALUES($1::uuid,$1::text || '@example.invalid','synthetic'),($2::uuid,$2::text || '@example.invalid','outsider')", [actor, outsider])
  await pool.query("INSERT INTO public.users(id,email,display_name) VALUES($1::uuid,$1::text || '@example.invalid','member'),($2::uuid,$2::text || '@example.invalid','system')", [member, system])
  await pool.query("INSERT INTO public.organization_members(organization_id,user_id,role) VALUES($1,$2,'owner'),($1,$3,'member'),($4,$3,'member'),($4,$5,'owner')", [org, actor, member, other, outsider])
  await pool.query('SELECT public.initialize_organization_schema($1)', [org])
  const legacyOwners = randomUUID(), legacyAdmin = randomUUID()
  await pool.query("INSERT INTO public.organizations(id,name,kind,service_status,use_platform_ai,created_by) VALUES($1,'legacy-owners','test','enabled',true,$3),($2,'legacy-admin','test','enabled',true,$3)", [legacyOwners, legacyAdmin, actor])
  await pool.query("INSERT INTO public.organization_members(organization_id,user_id,role) VALUES($1,$3,'owner'),($1,$4,'owner'),($2,$3,'admin')", [legacyOwners, legacyAdmin, actor, outsider])
  await pool.query("INSERT INTO public.enterprise_ai_settings(organization_id,base_url,api_key_ciphertext,model,self_service_enabled) VALUES($1,'https://ai.longdaoec.com','synthetic-unread-cipher','existing-own-model',true)", [legacyOwners])
  await check('migration upgrades pre-existing company and public tables without activating old credentials', async () => {
    await runMigrations(pool, migrations)
    for (const name of ['public', schema]) {
      const columns = await pool.query("SELECT column_default, is_nullable FROM information_schema.columns WHERE table_schema=$1 AND table_name='enterprise_ai_settings' AND column_name='self_service_enabled'", [name])
      assert.equal(columns.rows[0].column_default, 'false')
      assert.equal(columns.rows[0].is_nullable, 'NO')
    }
  })
  await pool.query('SELECT public.initialize_organization_schema($1)', [other])
  await check('migration preserves own-model priority, old grants and trusted chief administrators', async () => {
    const sources = (await pool.query('SELECT id,ai_model_source,use_platform_ai FROM public.organizations WHERE id=ANY($1::uuid[])', [[legacyOwners, legacyAdmin]])).rows
    assert.equal(sources.find(row => row.id===legacyOwners).ai_model_source, 'enterprise')
    assert.equal(sources.find(row => row.id===legacyAdmin).ai_model_source, 'platform')
    assert.ok(sources.every(row => row.use_platform_ai))
    const members = (await pool.query('SELECT organization_id,user_id,role,is_active FROM public.organization_members WHERE organization_id=ANY($1::uuid[])', [[legacyOwners, legacyAdmin]])).rows
    assert.equal(members.find(row => row.organization_id===legacyOwners && row.user_id===actor).role, 'owner')
    assert.equal(members.find(row => row.organization_id===legacyOwners && row.user_id===outsider).role, 'admin')
    assert.equal(members.find(row => row.organization_id===legacyAdmin).role, 'owner')
    assert.ok(members.every(row => row.is_active))
  })
  await new PlatformAiStore(pool, masterKey).save({ OPENAI_BASE_URL: 'https://platform.example/v1', OPENAI_API_KEY: 'synthetic-platform-key', OPENAI_MODEL: 'platform-model' }, actor)
  companyPool = new Pool({ ...connection, options: '-c search_path=' + schema + ',public' })
  otherPool = new Pool({ ...connection, options: '-c search_path=' + otherSchema + ',public' })
  const store = new EnterpriseAiStore(companyPool, masterKey), otherStore = new EnterpriseAiStore(otherPool, masterKey)
  await check('enterprise administrator saves encrypted credentials; newly created companies remain isolated', async () => {
    const view = await store.saveSelfService(org, { OPENAI_API_KEY: 'synthetic-company-secret', OPENAI_MODEL: 'company-model' }, actor)
    assert.equal(view.env.OPENAI_BASE_URL.value, SELF_SERVICE_AI_BASE_URL)
    assert.ok(!JSON.stringify(view).includes('synthetic-company-secret'))
    const row = (await companyPool.query('SELECT * FROM enterprise_ai_settings WHERE organization_id=$1', [org])).rows[0]
    assert.equal(row.self_service_enabled, true)
    assert.ok(!row.api_key_ciphertext.includes('synthetic-company-secret'))
    assert.equal((await otherStore.getSelfService(other)).apiKeyConfigured, false)
    await assert.rejects(otherStore.runtimeEnv(other), { code: 'ENTERPRISE_AI_NOT_CONFIGURED' })
    assert.equal((await pool.query('SELECT count(*)::int AS n FROM public.enterprise_ai_settings WHERE organization_id=ANY($1::uuid[])', [[org,other]])).rows[0].n, 0)
    assert.equal((await otherPool.query('SELECT count(*)::int AS n FROM enterprise_ai_settings')).rows[0].n, 0)
  })
  await check('model-only updates preserve key, fixed endpoint wins over tampered database URL', async () => {
    const ciphertext = (await companyPool.query('SELECT api_key_ciphertext FROM enterprise_ai_settings')).rows[0].api_key_ciphertext
    await store.saveSelfService(org, { OPENAI_MODEL: 'company-model-2' }, actor)
    assert.equal((await companyPool.query('SELECT api_key_ciphertext FROM enterprise_ai_settings')).rows[0].api_key_ciphertext, ciphertext)
    await companyPool.query("UPDATE enterprise_ai_settings SET base_url='https://attacker.invalid/v1'")
    const env = await store.runtimeEnv(org)
    assert.equal(env.OPENAI_BASE_URL, SELF_SERVICE_AI_BASE_URL + '/v1')
    assert.equal(env.OPENAI_API_KEY, 'synthetic-company-secret')
    assert.equal(env.OPENAI_MODEL, 'company-model-2')
    assert.equal((await store.selfServiceConnectionEnv(org)).OPENAI_BASE_URL, SELF_SERVICE_AI_BASE_URL + '/v1')
  })
  await check('nonmembers, endpoint changes and incomplete saves fail without modifying configuration', async () => {
    await assert.rejects(store.saveSelfService(org, { OPENAI_MODEL: 'forbidden' }, outsider), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await assert.rejects(store.saveSelfService(org, { OPENAI_BASE_URL: 'https://attacker.invalid' }, actor), { code: 'VALIDATION_ERROR' })
    assert.equal((await store.runtimeEnv(org)).OPENAI_MODEL, 'company-model-2')
    await assert.rejects(otherStore.saveSelfService(other, { OPENAI_MODEL: 'missing-key' }, actor), { code: 'WORKSPACE_ADMIN_REQUIRED' })
  })
  await check('clearing key fails closed and connection test never borrows the platform key', async () => {
    await store.saveSelfService(org, { OPENAI_API_KEY: '' }, actor)
    assert.equal((await store.getSelfService(org)).apiKeyConfigured, false)
    await assert.rejects(store.runtimeEnv(org), { code: 'ENTERPRISE_AI_NOT_CONFIGURED' })
    assert.equal((await store.selfServiceConnectionEnv(org)).OPENAI_API_KEY, '')
    const logs = await companyPool.query("SELECT metadata FROM audit_logs WHERE action='enterprise.ai_settings.update'")
    assert.equal(logs.rows.length, 3)
    assert.ok(!JSON.stringify(logs.rows).includes('synthetic-company-secret'))
    await assert.rejects(store.saveSelfService(org, { OPENAI_MODEL: 'missing-key' }, actor), { code: 'VALIDATION_ERROR' })
  })
  const { WorkspaceInvitationsService } = await import(pathToFileURL(join(projectRoot, 'apps/api/dist/src/auth/workspace-invitations.js')))
  const { PostgresSessionRepository } = await import(pathToFileURL(join(projectRoot, 'apps/api/dist/src/auth/session-repository.js')))
  const { PlatformUsersService } = await import(pathToFileURL(join(projectRoot, 'apps/api/dist/src/platform/users/service.js')))
  const { PlatformService } = await import(pathToFileURL(join(projectRoot, 'apps/api/dist/src/platform/service.js')))
  const { AiUsageService } = await import(pathToFileURL(join(projectRoot, 'apps/api/dist/src/platform/ai-usage.js')))
  const invitations = new WorkspaceInvitationsService(pool, true)
  const sessions = new PostgresSessionRepository(pool)
  const platformUsers = new PlatformUsersService(pool)
  const platform = new PlatformService(pool)
  process.env.SYSTEM_ADMIN_USER_NO = (await pool.query('SELECT user_no FROM public.users WHERE id=$1', [system])).rows[0].user_no
  await check('members and outsiders cannot administer enterprise AI, memberships or platform', async () => {
    await assert.rejects(store.assertAdmin(org, member), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await assert.rejects(store.saveSelfService(org, { OPENAI_API_KEY: 'member-key', OPENAI_MODEL: 'member-model' }, member), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await assert.rejects(store.selectSource(org, { modelSource: 'platform' }, member), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await assert.rejects(invitations.members(org, member), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await assert.rejects(invitations.setMemberStatus(other, actor, member, { isActive: false, reason: 'cross tenant denied' }), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await assert.rejects(platform.listCustomers(actor, new URLSearchParams()), { code: 'SYSTEM_ADMIN_REQUIRED' })
    await assert.rejects(platformUsers.appointWorkspaceOwner(actor, member, org, { reason: 'enterprise cannot appoint platform owner' }), { code: 'SYSTEM_ADMIN_REQUIRED' })
    assert.equal((await invitations.members(org, actor)).length, 2)
  })
  await check('chief administrator can appoint multiple subadministrators without granting platform or cross-company access', async () => {
    const secondAdmin = randomUUID(), invitedAdmin = randomUUID()
    await pool.query("INSERT INTO public.users(id,email,display_name) VALUES($1::uuid,$1::uuid::text || '@example.invalid','second-admin'),($2::uuid,$2::uuid::text || '@example.invalid','invited-admin')", [secondAdmin, invitedAdmin])
    await pool.query("INSERT INTO public.organization_members(organization_id,user_id,role) VALUES($1,$2,'member')", [org, secondAdmin])
    await Promise.all([member, secondAdmin].map(id => invitations.updateMember(org, actor, id, { membershipRole: 'admin' })))
    assert.equal((await pool.query("SELECT count(*)::int AS n FROM public.organization_members WHERE organization_id=$1 AND role='admin'", [org])).rows[0].n, 2)
    assert.equal((await pool.query("SELECT count(*)::int AS n FROM public.organization_members WHERE organization_id=$1 AND role='owner'", [org])).rows[0].n, 1)
    assert.equal((await sessions.listWorkspaces(member)).find(item => item.id === org).role, 'admin')
    await store.assertAdmin(org, member)
    await assert.rejects(otherStore.assertAdmin(other, member), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await assert.rejects(platform.listCustomers(member, new URLSearchParams()), { code: 'SYSTEM_ADMIN_REQUIRED' })
    await assert.rejects(invitations.updateMember(org, member, secondAdmin, { membershipRole: 'member' }), { code: 'FORBIDDEN' })
    await assert.rejects(invitations.updateMember(org, member, actor, { membershipRole: 'admin' }), { code: 'FORBIDDEN' })
    await assert.rejects(invitations.setMemberStatus(org, member, secondAdmin, { isActive: false, reason: 'cannot disable peer' }), { code: 'FORBIDDEN' })
    await assert.rejects(invitations.create(org, member, { membershipRole: 'admin' }), { code: 'VALIDATION_ERROR' })
    await assert.rejects(invitations.transferOwnership(org, member, secondAdmin, { reason: 'cannot transfer owner' }), { code: 'FORBIDDEN' })
    const invitation = await invitations.create(org, actor, {})
    assert.ok((await invitations.list(org, actor)).some(item => item.id === invitation.id))
    assert.ok((await invitations.list(org, member)).some(item => item.id === invitation.id))
    await invitations.accept(invitation.code, invitedAdmin)
    assert.equal((await sessions.listWorkspaces(invitedAdmin)).find(item => item.id === org).role, 'member')
    await invitations.updateMember(org, actor, invitedAdmin, { membershipRole: 'admin' })
    assert.equal((await sessions.listWorkspaces(invitedAdmin)).find(item => item.id === org).role, 'admin')
    await store.assertAdmin(org, invitedAdmin)
    await assert.rejects(platform.listCustomers(invitedAdmin, new URLSearchParams()), { code: 'SYSTEM_ADMIN_REQUIRED' })
    await invitations.setMemberStatus(org, actor, invitedAdmin, { isActive: false, reason: 'test suspension' })
    await assert.rejects(store.assertAdmin(org, invitedAdmin), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await invitations.setMemberStatus(org, actor, invitedAdmin, { isActive: true, reason: 'test restore' })
    await store.assertAdmin(org, invitedAdmin)
    await invitations.updateMember(org, actor, member, { membershipRole: 'member' })
    await assert.rejects(store.assertAdmin(org, member), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    const audit = await companyPool.query("SELECT id,metadata FROM audit_logs WHERE action='workspace.member.update' AND resource_id=$1 ORDER BY created_at", [member])
    assert.deepEqual(audit.rows.map(row => row.metadata.membershipRole), ['admin', 'member'])
    const mirror = await pool.query('SELECT id FROM public.audit_logs WHERE id=ANY($1::uuid[])', [audit.rows.map(row => row.id)])
    assert.equal(mirror.rows.length, 2)
  })
  await check('suspension invalidates selected enterprise immediately but preserves other memberships and global login', async () => {
    const user = await sessions.findUserById(member)
    const { session, token } = await sessions.createSession(user)
    await sessions.selectWorkspace(session.sessionId, member, org)
    assert.equal((await sessions.findSessionByToken(token)).user.workspaceId, org)
    await invitations.setMemberStatus(org, actor, member, { isActive: false, reason: 'temporary suspension' })
    const current = await sessions.findSessionByToken(token)
    assert.ok(current)
    assert.equal(current.user.workspaceId, undefined)
    assert.equal(current.user.workspaceAccessIssue, 'unavailable')
    assert.ok(!(await sessions.listWorkspaces(member)).some(item => item.id === org))
    assert.ok((await sessions.listWorkspaces(member)).some(item => item.id === other))
    await assert.rejects(sessions.selectWorkspace(session.sessionId, member, org))
    await assert.rejects(invitations.setMemberStatus(org, actor, actor, { isActive: false, reason: 'self denied' }), { code: 'FORBIDDEN' })
    await invitations.setMemberStatus(org, actor, member, { isActive: true, reason: 'restore access' })
    assert.equal((await sessions.selectWorkspace(session.sessionId, member, org)).workspaceId, org)
  })
  await check('ownership transfers atomically and platform can appoint without cross-tenant authority leaks', async () => {
    await invitations.transferOwnership(org, actor, member, { reason: 'handover test' })
    await store.assertAdmin(org, actor)
    assert.equal((await sessions.listWorkspaces(actor)).find(item => item.id === org).role, 'admin')
    await store.assertAdmin(org, member)
    await assert.rejects(pool.query("UPDATE public.organization_members SET role='owner' WHERE organization_id=$1 AND user_id=$2", [org, actor]), { code: '23505' })
    await assert.rejects(platformUsers.appointWorkspaceOwner(system, outsider, org, { reason: 'wrong company' }), { code: 'MEMBER_UNAVAILABLE' })
    await platformUsers.appointWorkspaceOwner(system, actor, org, { reason: 'restore administrator' })
    const owners = await pool.query("SELECT user_id FROM public.organization_members WHERE organization_id=$1 AND role='owner'", [org])
    assert.deepEqual(owners.rows.map(row => row.user_id), [actor])
    await assert.rejects(store.assertAdmin(org, member), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    assert.equal((await pool.query("SELECT count(*)::int AS n FROM public.platform_audit_logs WHERE organization_id=$1 AND action='platform.workspace.owner'", [org])).rows[0].n, 1)
  })
  await check('platform source requires an explicit enterprise grant and choice; withdrawal never falls back', async () => {
    await assert.rejects(store.selectSource(org, { modelSource: 'platform' }, actor), { code: 'PLATFORM_AI_NOT_AUTHORIZED' })
    await platformUsers.updateWorkspaceAiAccess(system, member, org, { usePlatformAi: true, reason: 'authorize company' })
    await assert.rejects(store.runtimeEnv(org), { code: 'ENTERPRISE_AI_NOT_CONFIGURED' })
    await store.selectSource(org, { modelSource: 'platform' }, actor)
    assert.equal((await store.runtimeEnv(org)).OPENAI_API_KEY, 'synthetic-platform-key')
    await store.saveSelfService(org, { OPENAI_API_KEY: 'restored-company-key', OPENAI_MODEL: 'restored-company-model' }, actor)
    assert.equal((await store.runtimeEnv(org)).OPENAI_MODEL, 'platform-model')
    await platformUsers.updateWorkspaceAiAccess(system, member, org, { usePlatformAi: false, reason: 'withdraw company grant' })
    await assert.rejects(store.runtimeEnv(org), { code: 'ENTERPRISE_AI_NOT_CONFIGURED' })
    await store.selectSource(org, { modelSource: 'enterprise' }, actor)
    assert.equal((await store.runtimeEnv(org)).OPENAI_MODEL, 'restored-company-model')
    await assert.rejects(otherStore.runtimeEnv(other), { code: 'ENTERPRISE_AI_NOT_CONFIGURED' })
  })
  await check('trial companies can exceed three executions without credit grants or trial deductions', async () => {
    await pool.query("UPDATE public.organizations SET service_status='trial',trial_ends_at=now()+interval '10 days' WHERE id=$1", [org])
    await pool.query('INSERT INTO public.organization_trial_ai_usage(organization_id,generations) VALUES($1,3) ON CONFLICT(organization_id) DO UPDATE SET generations=3', [org])
    const billing = new BillingStore(companyPool)
    const usage = new AiUsageService(companyPool)
    for (let n=0; n<5; n++) {
      const ticket = await billing.reserve({ organizationId: org, operation: 'job_spec', key: 'test-no-charge-'+n, input: { n }, amount: 1 })
      assert.equal(ticket.units, 0)
      await billing.finish(ticket.id, 'settled', { n })
      const result = await usage.execute({ organizationId: org, actorId: member, operation: 'jd', resourceId: randomUUID(), key: 'usage-no-trial-'+n, input: { n }, model: 'synthetic-no-network' }, async () => ({ n }))
      assert.equal(result.n, n)
    }
    assert.equal((await pool.query('SELECT count(*)::int AS n FROM public.billing_grants WHERE organization_id=$1', [org])).rows[0].n, 0)
    assert.equal((await pool.query('SELECT generations FROM public.organization_trial_ai_usage WHERE organization_id=$1', [org])).rows[0].generations, 3)
    await assert.rejects(usage.read(member, org), { code: 'WORKSPACE_ADMIN_REQUIRED' })
    await invitations.setMemberStatus(org, actor, member, { isActive: false, reason: 'reject model dispatch' })
    await assert.rejects(usage.execute({ organizationId: org, actorId: member, operation: 'jd', resourceId: randomUUID(), key: 'usage-disabled-member', input: {}, model: 'synthetic' }, async () => { throw Error('must not dispatch') }), { code: 'WORKSPACE_SERVICE_UNAVAILABLE' })
    await invitations.setMemberStatus(org, actor, member, { isActive: true, reason: 'restore after test' })
  })
  const { PaymentService } = await import(pathToFileURL(join(projectRoot, 'apps/api/dist/src/payments/service.js')))
  const payments = new PaymentService(pool, undefined, { SYSTEM_ADMIN_USER_NO: process.env.SYSTEM_ADMIN_USER_NO })
  await check('enterprise checkout exposes subscriptions only without legacy balances or grants', async () => {
    const before = (await pool.query('SELECT count(*)::int AS n FROM public.billing_grants')).rows[0].n
    const checkout = await payments.checkout(actor, org)
    assert.equal(Object.hasOwn(checkout, 'billing'), false)
    assert.ok(checkout.products.every(product => product.billingKind === 'subscription' && Object.keys(product.billingEntitlements).length === 0))
    assert.ok(checkout.orders.every(order => order.billingKind === 'subscription'))
    const status = await payments.enterpriseBilling(actor, org)
    assert.equal(status.enabled, false)
    assert.deepEqual(status.resources, [])
    assert.deepEqual(status.tasks, [])
    assert.deepEqual(status.grants, [])
    assert.deepEqual(status.rules, {})
    assert.ok(status.execution)
    assert.equal((await pool.query('SELECT count(*)::int AS n FROM public.billing_grants')).rows[0].n, before)
    await assert.rejects(payments.checkout(member, org), { code: 'WORKSPACE_ADMIN_REQUIRED' })
  })
  await check('retired compute writes cannot be reopened through old API clients', async () => {
    await assert.rejects(payments.convertCredits(system, {}), { code: 'COMPUTE_BILLING_RETIRED' })
    await assert.rejects(payments.grantBillingQuota(system, {}), { code: 'COMPUTE_BILLING_RETIRED' })
    await assert.rejects(payments.publishProduct(system, { billingKind: 'addon' }), { code: 'COMPUTE_BILLING_RETIRED' })
    await assert.rejects(payments.publishProduct(system, { billingKind: 'subscription', billingEntitlements: { quotas: { ai_points: 1 } } }), { code: 'COMPUTE_BILLING_RETIRED' })
    await assert.rejects(payments.convertCredits(member, {}), { code: 'SYSTEM_ADMIN_REQUIRED' })
  })
  console.log(JSON.stringify({ passed: true, checks: checks.length, boundary: 'dedicated synthetic PostgreSQL; no external model calls' }))
} finally {
  await companyPool?.end(); await otherPool?.end(); await pool?.end()
  if (created) await admin.query('DROP DATABASE "' + instance.database + '" WITH (FORCE)')
  await admin.end(); await instance.stop()
}
